const express = require('express');
const c = require('../controllers/turnoController');
const { requerirSesion } = require('../controllers/authController');
const { requerirRol, requerirPerfilCompleto } = require('../middleware/autorizacion');
const router = express.Router();
router.get('/profesionales/opciones', c.opcionesPublicas);
router.get('/profesionales', c.buscar);
router.get('/profesionales/:id/disponibilidad', c.disponibilidad);
router.get('/profesionales/:id', require('../controllers/perfilProfesionalController').obtenerPublico);
router.use(requerirSesion, requerirPerfilCompleto);
router.get('/turnos', requerirRol('PSICOLOGO', 'PACIENTE'), c.listar);
router.get('/turnos/opciones', requerirRol('PSICOLOGO'), c.opcionesProfesional);
router.put('/turnos/coberturas', requerirRol('PSICOLOGO'), c.coberturas);
router.post('/turnos', requerirRol('PSICOLOGO'), c.crear);
router.put('/turnos/:id', requerirRol('PSICOLOGO'), c.editar);
router.delete('/turnos/:id', requerirRol('PSICOLOGO'), c.eliminar);
router.post('/turnos/:id/reservar', requerirRol('PACIENTE'), c.reservar);
router.post('/turnos/:id/cancelar', requerirRol('PACIENTE', 'PSICOLOGO'), c.cancelar);
module.exports = router;
